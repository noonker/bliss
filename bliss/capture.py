"""Capture the two things that are not the system: files and environment."""

from __future__ import annotations

import fnmatch
import os
import re
import shlex
import stat
import tarfile
from pathlib import Path

# Describes this login/terminal rather than the workload, so meaningless or
# actively wrong elsewhere.
_SESSION_VARS = {
    "HOME", "USER", "LOGNAME", "SHELL", "PWD", "OLDPWD", "SHLVL", "HOSTNAME", "_",
    "TERM", "COLORTERM", "TERM_PROGRAM", "TERM_PROGRAM_VERSION", "TERMCAP",
    "DISPLAY", "WAYLAND_DISPLAY", "XAUTHORITY", "XDG_RUNTIME_DIR", "XDG_SESSION_ID",
    "XDG_SESSION_TYPE", "XDG_SESSION_CLASS", "XDG_SEAT", "XDG_VTNR",
    "XDG_CONFIG_HOME", "XDG_CACHE_HOME", "XDG_DATA_HOME", "XDG_STATE_HOME",
    "DBUS_SESSION_BUS_ADDRESS", "SSH_AUTH_SOCK", "SSH_AGENT_PID", "SSH_CONNECTION",
    "SSH_CLIENT", "SSH_TTY", "GPG_AGENT_INFO", "TMUX", "TMUX_PANE", "STY", "WINDOW",
    "GUIX_ENVIRONMENT", "GUIX_PROFILE", "GUIX_LOCPATH", "GUILE_LOAD_PATH",
    "GUILE_LOAD_COMPILED_PATH", "NIX_PROFILES", "NIX_PATH", "NIX_REMOTE",
    "LD_LIBRARY_PATH", "LD_PRELOAD", "SSL_CERT_DIR", "SSL_CERT_FILE",
    "CURL_CA_BUNDLE", "GIT_SSL_CAINFO", "NIX_SSL_CERT_FILE", "BLISS_CONFIG",
    "BLISS_DEBUG",
}
_SESSION_PREFIXES = ("CLAUDE_CODE_", "BASH_FUNC_", "LESS_TERMCAP_", "XDG_CURRENT_", "VTE_")

_STORE_RE = re.compile(r"^/(gnu|nix)/store/")
PROFILE_MARK = "\x00profile\x00"
WORK_MARK = "\x00work\x00"


def _host_only(item: str, profile: str | None, closure: set[str], home: str, cwd: str) -> bool:
    """True for a path that cannot exist on the target."""
    if profile and item.startswith(profile):
        return False
    if item == cwd or item.startswith(cwd + "/"):
        return False  # travels with the files
    if _STORE_RE.match(item):
        root = "/".join(item.split("/")[:4])
        return root not in closure
    if item.startswith("/run/current-system") or item.startswith("/etc/profiles"):
        return True
    return bool(home) and (item == home or item.startswith(home + "/"))


def capture_env(environ: dict[str, str], *, profile: str | None, closure: set[str],
                cwd: str, settings: dict | None = None) -> dict[str, str]:
    """The env to reproduce, with host-only paths removed.

    The profile's store path changes when it is re-packed and the working
    directory moves, so both become markers that env_script() turns back into
    shell variables on the target.
    """
    settings = settings or {}
    excluded = settings.get("exclude", [])
    included = settings.get("include", [])
    home = environ.get("HOME", "")
    result: dict[str, str] = {}
    for name, value in environ.items():
        if any(fnmatch.fnmatchcase(name, pat) for pat in included):
            result[name] = value
            continue
        if (name in _SESSION_VARS or name.startswith(_SESSION_PREFIXES)
                or any(fnmatch.fnmatchcase(name, pat) for pat in excluded)):
            continue
        items = value.split(":")
        if any(i.startswith("/") for i in items):
            kept = [i for i in items if not i.startswith("/")
                    or not _host_only(i, profile, closure, home, cwd)]
            if not kept:
                continue
            value = ":".join(kept)
        if profile:
            value = value.replace(profile, PROFILE_MARK)
        result[name] = _replace_path(value, cwd, WORK_MARK)
    return result


# Only what describes the terminal this happens to run in. Everything else
# stays exactly as it is, because the workload is staying on this machine.
_NOT_HERE = {"TMUX", "TMUX_PANE", "STY", "WINDOW", "TERM", "TERMCAP", "COLORTERM", "PWD", "OLDPWD",
             "SHLVL", "_"}


def here_env(environ: dict[str, str]) -> dict[str, str]:
    """The environment for a workload that runs in place."""
    return {name: value for name, value in environ.items() if name not in _NOT_HERE}


def _replace_path(value: str, path: str, mark: str) -> str:
    """Replace `path` only where it ends at a path boundary."""
    return re.sub(re.escape(path) + r"(?=$|[/:])", lambda _: mark, value)


def _quote(value: str) -> str:
    """Single-quote `value`, leaving its markers as live shell variables."""
    parts = re.split(f"({PROFILE_MARK}|{WORK_MARK})", value)
    out = []
    for part in parts:
        if part == PROFILE_MARK:
            out.append('"$BLISS_PROFILE"')
        elif part == WORK_MARK:
            out.append('"$BLISS_WORK"')
        elif part:
            out.append(shlex.quote(part))
    return "".join(out) or "''"


def env_script(env: dict[str, str]) -> str:
    lines = ["# generated by bliss; may contain secrets"]
    for name in sorted(env):
        if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
            lines.append(f"export {name}={_quote(env[name])}")
    return "\n".join(lines) + "\n"


class Ignore:
    """A .blissignore: gitignore-style globs (no negation)."""

    def __init__(self, patterns: list[str]):
        self.patterns = [p.strip() for p in patterns
                         if p.strip() and not p.lstrip().startswith("#")]

    @classmethod
    def for_dir(cls, root: Path) -> "Ignore":
        patterns = [".bliss/"]
        ignore_file = root / ".blissignore"
        if ignore_file.exists():
            patterns += ignore_file.read_text().splitlines()
        return cls(patterns)

    def matches(self, rel: str, is_dir: bool) -> bool:
        name = rel.rsplit("/", 1)[-1]
        for pattern in self.patterns:
            dir_only = pattern.endswith("/")
            pat = pattern.rstrip("/")
            if dir_only and not is_dir:
                continue
            if "/" in pat:
                if fnmatch.fnmatchcase(rel, pat.lstrip("/")):
                    return True
            elif fnmatch.fnmatchcase(name, pat):
                return True
        return False


def tar_directory(root: Path, fileobj, arcname: str = "") -> tuple[int, int]:
    """Write `root` to a tar stream, honouring .blissignore.

    Returns (file count, total bytes).
    """
    ignore = Ignore.for_dir(root)
    count = size = 0
    with tarfile.open(fileobj=fileobj, mode="w|") as tar:
        for dirpath, dirnames, filenames in os.walk(root):
            rel_dir = os.path.relpath(dirpath, root)
            rel_dir = "" if rel_dir == "." else rel_dir
            dirnames[:] = sorted(d for d in dirnames
                                 if not ignore.matches(os.path.join(rel_dir, d), True))
            for name in [*dirnames, *sorted(filenames)]:
                rel = os.path.join(rel_dir, name)
                full = os.path.join(root, rel)
                info = os.lstat(full)
                if stat.S_ISDIR(info.st_mode):
                    pass
                elif not (stat.S_ISREG(info.st_mode) or stat.S_ISLNK(info.st_mode)):
                    continue  # sockets, fifos and devices do not travel
                elif ignore.matches(rel, False):
                    continue
                member = tar.gettarinfo(full, arcname=os.path.join(arcname, rel))
                member.uid = member.gid = 0
                member.uname = member.gname = ""
                if member.isreg():
                    with open(full, "rb") as handle:
                        tar.addfile(member, handle)
                    count += 1
                    size += member.size
                else:
                    tar.addfile(member)
    return count, size
