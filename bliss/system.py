"""Turn the current Guix or Nix shell into something that runs elsewhere."""

from __future__ import annotations

import hashlib
import io
import json
import os
import re
import tarfile
from dataclasses import dataclass
from pathlib import Path

from .agents import Agent, Release
from .util import BlissError, cache_dir, has_tool, log, output, run

_BASE_GUIX = ("bash", "coreutils", "tar", "gzip", "nss-certs", "sed", "grep")
_BASE_NIX = ("bashInteractive", "coreutils", "gnutar", "gzip", "cacert")
LOADER = "/lib64/ld-linux-x86-64.so.2"


@dataclass
class AgentSpec:
    agent: Agent
    release: Release


@dataclass
class Pack:
    """A built system, and how run.sh finds things inside it."""
    # docker-archive: load into a container engine
    # relocatable:    a tar to unpack anywhere (guix pack -RR)
    # nix-closure:    store paths to `nix copy`
    format: str
    key: str
    path: str | None = None
    store_paths: tuple[str, ...] = ()
    # Shell expressions, valid on the target once $BLISS_PROFILE is set.
    bin_dirs: tuple[str, ...] = ()
    ca_file: str = ""
    loader: str = ""
    patchelf: str = ""
    agent_root: str = ""
    bash: str = "/bin/bash"
    uses_profile: bool = False


class System:
    name = "base"

    def profile(self) -> str | None:
        raise NotImplementedError

    def closure(self) -> set[str]:
        raise NotImplementedError

    def describe(self) -> str:
        raise NotImplementedError

    def build(self, fmt: str, spec: AgentSpec | None) -> Pack:
        raise NotImplementedError


def _scheme(value: str) -> str:
    return json.dumps(value)  # JSON string escapes are valid Scheme here


def _guix_agent_package(spec: AgentSpec) -> str:
    """A fixed-output package holding the agent's unmodified release files."""
    agent, rel = spec.agent, spec.release
    if agent.kind == "binary":
        install = f"""
      (let ((b (string-append #$output "/bin/{agent.name}")))
        (mkdir-p (dirname b))
        (copy-file #+source b)
        (chmod b #o755))"""
    else:
        executable = "/".join(p for p in ("../libexec", agent.name, agent.bin_rel, agent.name) if p)
        install = f"""
      (let ((dest (string-append #$output "/libexec/{agent.name}")))
        (setenv "PATH" (string-append #+tar "/bin:" #+gzip "/bin"))
        (mkdir-p dest)
        (invoke "tar" "xzf" #+source "-C" dest "--strip-components=1")
        (mkdir-p (string-append #$output "/bin"))
        (symlink {_scheme(executable)}
                 (string-append #$output "/bin/{agent.name}")))"""
    return f"""
(define bliss-agent
  (package
    (name "bliss-agent-{agent.name}")
    (version {_scheme(rel.version.lstrip("v"))})
    (source (origin
              (method url-fetch)
              (uri {_scheme(rel.url)})
              (sha256 (base16-string->bytevector {_scheme(rel.sha256)}))))
    (build-system trivial-build-system)
    (arguments
     (list #:modules '((guix build utils))
           #:builder
           #~(begin
               (use-modules (guix build utils)){install})))
    (home-page {_scheme(rel.url)})
    (synopsis "Unmodified release of {agent.name}, fetched by bliss")
    (description "Unmodified release of {agent.name}, fetched by bliss.")
    (license #f)))
"""


def guix_manifest(profile: str | None, spec: AgentSpec | None) -> str:
    """A manifest for the shell's exact store items, plus what bliss needs."""
    extras = list(_BASE_GUIX)
    agent_scm = ""
    agent_entry = ""
    gcc_entry = ""
    if spec:
        if spec.agent.gcc_runtime:
            # Only the "lib" output: the libraries without the whole compiler.
            gcc_entry = '(packages->manifest (list (list (@ (gnu packages gcc) gcc) "lib")))'
        extras += ["glibc", "patchelf", *spec.agent.guix_deps]
        if spec.agent.kind != "installer":
            agent_scm = _guix_agent_package(spec)
            agent_entry = "(packages->manifest (list bliss-agent))"
    shell = f"(profile-manifest {_scheme(profile)})" if profile else "(manifest '())"
    specs = " ".join(_scheme(s) for s in dict.fromkeys(extras))
    return f""";; generated by bliss
(use-modules (guix profiles) (guix packages) (guix download) (guix gexp)
             (guix base16) (guix build-system trivial)
             (gnu packages) (gnu packages base) (gnu packages compression))
{agent_scm}
(define shell {shell})
(define have (map manifest-entry-name (manifest-entries shell)))
(concatenate-manifests
 (list shell
       (specifications->manifest
        (filter (lambda (s) (not (member s have))) '({specs})))
       ;; A hidden package, so it has no spec; far smaller than glibc-locales.
       (if (member "glibc-utf8-locales" have)
           (manifest '())
           (packages->manifest (list glibc-utf8-locales)))
       {agent_entry}
       {gcc_entry}))
"""


class GuixSystem(System):
    name = "guix"

    def __init__(self, environ: dict[str, str]):
        self._profile = environ.get("GUIX_ENVIRONMENT")
        if not self._profile:
            log("warning: not in a 'guix shell', so only base tools will be packed")

    def profile(self) -> str | None:
        return self._profile

    def closure(self) -> set[str]:
        if not self._profile:
            return set()
        return set(output(["guix", "gc", "-R", self._profile]).split())

    def describe(self) -> str:
        return f"guix shell {self._profile}" if self._profile else "guix (no shell)"

    def build(self, fmt: str, spec: AgentSpec | None) -> Pack:
        text = guix_manifest(self._profile, spec)
        key = hashlib.sha256(text.encode()).hexdigest()[:16]
        manifest = cache_dir() / "manifests" / f"{key}.scm"
        manifest.parent.mkdir(parents=True, exist_ok=True)
        manifest.write_text(text)
        cmd = ["guix", "pack", "-m", str(manifest), "-S", "/bin=bin"]
        if fmt == "docker-archive":
            cmd += ["-f", "docker", f"--image-tag=bliss-sys:{key}",
                    "-S", "/usr/bin/env=bin/env"]
            if spec:
                # A real loader path, so release binaries run unmodified.
                cmd += ["-S", f"{LOADER}=lib/ld-linux-x86-64.so.2"]
        elif fmt == "relocatable":
            cmd += ["-RR"]
        else:
            raise BlissError(f"guix cannot build pack format {fmt}")
        log("building system pack with guix (cached after the first build)")
        path = run(cmd, stdout=-1).stdout.decode().strip().splitlines()[-1]
        return Pack(format=fmt, key=hashlib.sha256(path.encode()).hexdigest()[:16],
                    path=path, uses_profile=True, bin_dirs=("$BLISS_PROFILE/bin",),
                    ca_file="$BLISS_PROFILE/etc/ssl/certs/ca-certificates.crt",
                    loader="$BLISS_PROFILE/lib/ld-linux-x86-64.so.2",
                    patchelf="$BLISS_PROFILE/bin/patchelf",
                    agent_root="$BLISS_PROFILE")


_NIX_PATH_RE = re.compile(r"/nix/store/[a-z0-9]{32}-[^/:\s\"']+")


def nix_shell_roots(environ: dict[str, str]) -> list[str]:
    """Store paths a nix-shell / nix develop environment refers to.

    Unlike a Guix profile there is no single store item, so the environment
    itself is the only description of the shell.
    """
    roots: set[str] = set()
    for name, value in environ.items():
        if name not in ("NIX_PROFILES",):
            roots.update(_NIX_PATH_RE.findall(value))
    # $out and friends name outputs of the shell's derivation, which never get built.
    return sorted(r for r in roots if os.path.exists(r))


class NixSystem(System):
    name = "nix"

    def __init__(self, environ: dict[str, str]):
        self._roots = nix_shell_roots(environ)
        if not environ.get("IN_NIX_SHELL"):
            log("warning: not in a nix shell, so only base tools and paths "
                "named by the environment will be packed")

    def profile(self) -> str | None:
        return None

    def closure(self) -> set[str]:
        return self._close(self._roots)

    def describe(self) -> str:
        return f"nix shell ({len(self._roots)} store paths in env)"

    @staticmethod
    def _close(roots: list[str]) -> set[str]:
        if not roots:
            return set()
        return set(output(["nix-store", "-qR", *roots]).split())

    @staticmethod
    def _realise(attr: str) -> str:
        """Build a package's main output on both flake and channel setups."""
        if has_tool("nix"):
            proc = run(["nix", "--extra-experimental-features", "nix-command flakes",
                        "build", "--no-link", "--print-out-paths", attr if "#" in attr
                        else f"nixpkgs#{attr}^out"], capture=True, check=False)
            if proc.returncode == 0:
                return proc.stdout.decode().split()[0]
        if "#" in attr:
            raise BlissError(f"could not build {attr} with nix")
        return output(["nix-build", "<nixpkgs>", "-A", f"{attr}.out", "--no-out-link"]).split()[0]

    @staticmethod
    def _fetch_release(spec: AgentSpec) -> str:
        """Fetch one file into the store, verified against the release's checksum."""
        is_binary = spec.agent.kind == "binary"
        proc = output(["nix-prefetch-url", "--type", "sha256",
                       *(["--executable"] if is_binary else []),
                       "--name", spec.agent.name if is_binary else f"{spec.agent.name}.tar.gz",
                       "--print-path",
                       spec.release.url, spec.release.sha256])
        return proc.splitlines()[-1]

    def build(self, fmt: str, spec: AgentSpec | None) -> Pack:
        log("gathering system with nix (cached after the first build)")
        base = {name: self._realise(name) for name in _BASE_NIX}
        libc = self._realise("glibc")
        extras = [*base.values(), libc]
        agent_root = ""
        patchelf = ""
        bin_dirs = [f"{base['bashInteractive']}/bin", f"{base['coreutils']}/bin",
                    f"{base['gnutar']}/bin", f"{base['gzip']}/bin"]
        if spec:
            patchelf_pkg = self._realise("patchelf")
            patchelf = f"{patchelf_pkg}/bin/patchelf"
            extras.append(patchelf_pkg)
            for dep in spec.agent.nix_deps:
                path = self._realise(dep)
                extras.append(path)
                bin_dirs.append(f"{path}/bin")
            if spec.agent.flake:
                agent_root = self._realise(spec.agent.flake)
                extras.append(agent_root)
                bin_dirs.append(f"{agent_root}/bin")
            elif spec.agent.kind in ("binary", "tarball"):
                # A tarball's checksum covers the archive, so it travels unpacked
                # and is unpacked on the target by prepare_agent_script().
                agent_root = self._fetch_release(spec)
                extras.append(agent_root)
        paths = sorted(self._close([*self._roots, *extras]))
        key = hashlib.sha256("\n".join(paths).encode()).hexdigest()[:16]
        pack = Pack(format=fmt, key=key, store_paths=tuple(paths), bin_dirs=tuple(bin_dirs),
                    ca_file=f"{base['cacert']}/etc/ssl/certs/ca-bundle.crt",
                    loader=f"{libc}/lib/ld-linux-x86-64.so.2", patchelf=patchelf,
                    agent_root=agent_root, bash=f"{base['bashInteractive']}/bin/bash")
        if fmt == "docker-archive":
            archive = cache_dir() / "packs" / f"nix-{key}.tar"
            if not archive.exists():
                archive.parent.mkdir(parents=True, exist_ok=True)
                write_docker_archive(archive, paths, bin_dirs, pack.loader,
                                     f"bliss-sys:{key}")
            pack.path = str(archive)
        elif fmt == "relocatable":
            pack.format = "nix-closure"
        return pack


def _add_symlink(tar: tarfile.TarFile, name: str, target: str) -> None:
    info = tarfile.TarInfo(name)
    info.type = tarfile.SYMTYPE
    info.linkname = target
    info.mode = 0o777
    tar.addfile(info)


def _add_dir(tar: tarfile.TarFile, name: str) -> None:
    info = tarfile.TarInfo(name)
    info.type = tarfile.DIRTYPE
    info.mode = 0o755
    tar.addfile(info)


def write_docker_archive(dest: Path, store_paths: list[str], bin_dirs: list[str],
                         loader: str, tag: str) -> None:
    """A one-layer docker-archive of store paths, with an FHS shim on top.

    Nix has no equivalent of `guix pack` without pulling in nixpkgs' dockerTools
    and an expression for the shell, and a closure is all this needs.
    """
    tmp = dest.with_suffix(".tmp")
    layer = dest.with_suffix(".layer")
    with tarfile.open(layer, "w") as tar:
        for name in ("nix", "nix/store", "bin", "usr", "usr/bin", "lib64"):
            _add_dir(tar, name)
        for path in store_paths:
            tar.add(path, arcname=path.lstrip("/"), recursive=True)
        seen: set[str] = set()
        for bin_dir in bin_dirs:
            if not os.path.isdir(bin_dir):
                continue
            for entry in sorted(os.listdir(bin_dir)):
                if entry not in seen:
                    seen.add(entry)
                    _add_symlink(tar, f"bin/{entry}", f"{bin_dir}/{entry}")
        if "sh" not in seen and "bash" in seen:
            _add_symlink(tar, "bin/sh", "bash")
        _add_symlink(tar, "usr/bin/env", "/bin/env")
        _add_symlink(tar, "lib64/ld-linux-x86-64.so.2", loader)
    digest = hashlib.sha256()
    with open(layer, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    diff_id = digest.hexdigest()
    config = json.dumps({
        "architecture": "amd64", "os": "linux",
        "config": {"Env": ["PATH=/bin"]},
        "rootfs": {"type": "layers", "diff_ids": [f"sha256:{diff_id}"]},
    }).encode()
    config_name = hashlib.sha256(config).hexdigest() + ".json"
    manifest = json.dumps([{"Config": config_name, "RepoTags": [tag],
                            "Layers": [f"{diff_id}/layer.tar"]}]).encode()
    with tarfile.open(tmp, "w") as tar:
        tar.add(layer, arcname=f"{diff_id}/layer.tar")
        for name, data in ((config_name, config), ("manifest.json", manifest)):
            info = tarfile.TarInfo(name)
            info.size = len(data)
            tar.addfile(info, io.BytesIO(data))
    layer.unlink()
    tmp.replace(dest)


def detect_system(environ: dict[str, str]) -> System:
    """Which package manager's shell this is; a shell beats what is installed."""
    if environ.get("GUIX_ENVIRONMENT"):
        return GuixSystem(environ)
    if environ.get("IN_NIX_SHELL"):
        return NixSystem(environ)
    if has_tool("guix"):
        return GuixSystem(environ)
    if has_tool("nix-store"):
        return NixSystem(environ)
    raise BlissError("neither guix nor nix found; bliss needs one to pack the system")
